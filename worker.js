/* ==================== 路由 ==================== */
export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const path = url.pathname.replace(/\/+$/, '') || '/';

    if (request.method === 'OPTIONS') {
      return new Response(null, {
        status: 204,
        headers: {
          'Access-Control-Allow-Origin': '*',
          'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
          'Access-Control-Allow-Headers': 'Content-Type',
        },
      });
    }

    try {
      switch (path) {
        case '/':
        case '/index.html':
          return htmlPage(HTML);
        case '/favicon.ico':
        case '/favicon.svg':
          return new Response(FAVICON, {
            status: 200,
            headers: { 'Content-Type': 'image/svg+xml', 'Cache-Control': 'public, max-age=604800' },
          });
        case '/api/geo':
          return handleGeo(request);
        case '/api/rates':
          return json(await cached('rates', 600, fetchRates));
        case '/api/crypto':
          return json(await cached('crypto', 120, fetchCrypto));
        case '/api/weather':
          return json(await handleWeather(url, request));
        case '/api/dns':
          return handleDns(url);
        case '/api/guestbook':
          return handleGuestbook(request, env);
        case '/api/stats':
          return handleStats(request, env, ctx);
        case '/api/health':
          return json({ ok: true, service: 'edge-hub', time: new Date().toISOString(), kv: !!env.EDGEHUB_KV });
        default:
          return json({ ok: false, error: 'Not Found', path }, 404);
      }
    } catch (e) {
      return json({ ok: false, error: e.message || '服务器内部错误' }, 500);
    }
  },
};
