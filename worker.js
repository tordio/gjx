/* ==================== 缓存（Cache API 优先，降级内存） ==================== */
const mem = new Map();
async function cacheGet(key) {
  const m = mem.get(key);
  if (m && m.exp > Date.now()) return m.v;
  try {
    if (typeof caches !== 'undefined' && caches.default) {
      const hit = await caches.default.match('https://edgehub.internal/' + key);
      if (hit) {
        const v = await hit.json();
        mem.set(key, { v, exp: Date.now() + 60000 });
        return v;
      }
    }
  } catch (e) { /* 忽略 */ }
  return null;
}
async function cachePut(key, val, ttl) {
  mem.set(key, { v: val, exp: Date.now() + ttl * 1000 });
  try {
    if (typeof caches !== 'undefined' && caches.default) {
      await caches.default.put(
        'https://edgehub.internal/' + key,
        new Response(JSON.stringify(val), { headers: { 'Cache-Control': 'max-age=' + ttl } })
      );
    }
  } catch (e) { /* 忽略 */ }
}
async function cached(key, ttl, producer) {
  const hit = await cacheGet(key);
  if (hit) return Object.assign({}, hit, { cached: true });
  try {
    const val = await producer();
    await cachePut(key, val, ttl);
    return Object.assign({}, val, { cached: false });
  } catch (e) {
    const stale = mem.get(key);
    if (stale) return Object.assign({}, stale.v, { cached: true, stale: true });
    return { ok: false, error: e.message || '数据源不可用' };
  }
}
async function fetchJson(url, opts = {}) {
  const res = await fetch(url, Object.assign({
    headers: { 'User-Agent': 'EdgeHub/1.0', Accept: 'application/json' },
  }, opts));
  if (!res.ok) throw new Error('HTTP ' + res.status);
  return res.json();
}

